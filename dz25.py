import math


class Rectangle:
    """
    Класс, описывающий прямоугольник.
    Свойства (длина и ширина) сделаны защищёнными (private) через двойное подчёркивание.
    """

    def __init__(self, length, width):
        """
        Конструктор класса. Инициализирует длину и ширину прямоугольника.
        :param length: длина прямоугольника
        :param width: ширина прямоугольника
        """
        # Защищённые (приватные) поля — доступны только внутри класса
        self.__length = length
        self.__width = width


    def area(self):
        """
        Вычисляет площадь прямоугольника по формуле: S = длина * ширина.
        :return: площадь прямоугольника
        """
        return self.__length * self.__width

    def perimeter(self):
        """
        Вычисляет периметр прямоугольника по формуле: P = 2 * (длина + ширина).
        :return: периметр прямоугольника
        """
        return 2 * (self.__length + self.__width)

    def diagonal(self):
        """
        Вычисляет диагональ (гипотенузу) прямоугольника
        по теореме Пифагора: d = sqrt(длина^2 + ширина^2).
        :return: длина диагонали
        """
        return math.sqrt(self.__length ** 2 + self.__width ** 2)


    def draw(self):
        """
        Рисует прямоугольник в консоли из звёздочек (*).
        Ширина рисунка = длина прямоугольника, высота = ширина (в символах).
        Для наглядности значения ограничены разумными пределами.
        """
        print()  # пустая строка перед рисунком
        for _ in range(self.__width):
            print("*" * self.__length)



    def display_info(self):
        """
        Выводит полную информацию о прямоугольнике:
        длину, ширину, площадь, периметр и диагональ.
        """
        print(f"Длина прямоугольника: {self.__length}")
        print(f"Ширина прямоугольника: {self.__width}")
        print(f"Площадь прямоугольника: {self.area()}")
        print(f"Периметр прямоугольника: {self.perimeter()}")
        # :.2f — округление диагонали до 2 знаков после запятой
        print(f"Гипотенуза прямоугольника: {self.diagonal():.2f}")



if __name__ == "__main__":

    rect = Rectangle(3, 9)


    rect.display_info()


    rect.draw()

